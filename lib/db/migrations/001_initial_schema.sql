CREATE TABLE schema_migrations (
  version TEXT PRIMARY KEY,
  applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE seating_arrangements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  exam_date TEXT NOT NULL CHECK (btrim(exam_date) <> ''),
  slot TEXT,
  pdf_name TEXT NOT NULL CHECK (btrim(pdf_name) <> ''),
  pdf_path TEXT NOT NULL CHECK (btrim(pdf_path) <> ''),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE UNIQUE INDEX idx_seating_arrangements_one_active
  ON seating_arrangements (is_active)
  WHERE is_active = TRUE;

CREATE TABLE students (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  arrangement_id BIGINT NOT NULL
    REFERENCES seating_arrangements (id)
    ON DELETE CASCADE,
  name TEXT NOT NULL CHECK (btrim(name) <> ''),
  roll_no TEXT NOT NULL CHECK (btrim(roll_no) <> ''),
  room_no TEXT NOT NULL CHECK (btrim(room_no) <> ''),
  seat_no TEXT NOT NULL CHECK (btrim(seat_no) <> ''),
  CONSTRAINT idx_students_unique_roll
    UNIQUE (arrangement_id, roll_no),
  CONSTRAINT idx_students_unique_seat
    UNIQUE (arrangement_id, room_no, seat_no)
);

CREATE INDEX idx_students_roll_no ON students (roll_no);
CREATE INDEX idx_students_name ON students (name);

